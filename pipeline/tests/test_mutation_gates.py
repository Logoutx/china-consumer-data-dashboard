# ===========================================================================


def test_mut_unit_slip(tmp_path):
    real = load_fixture_series("mut-retail-total")
    real_history = copy.deepcopy(real)
    real_history["observations"] = real_history["observations"][:-1]  # "not on file yet"
    period = real["observations"][-1]["period"]

    def make(m_value):
        staged = copy.deepcopy(real)
        staged["observations"][-1]["m"] = m_value
        batch = make_batch([touch("mut-retail-total", period, m=m_value)])
        return make_context(
            tmp_path / f"case-{m_value}",
            real_overrides={"mut-retail-total": real_history},
            staged_overrides={"mut-retail-total": staged},
            batch=batch,
            today=TODAY,
            archive_files={"nbs-retail": ["rel:test"]},  # keep gate_a.archive_release_identity quiet; not this test's concern
        )

    clean_ctx = make(real["observations"][-1]["m"])
    assert check_unit_magnitude(clean_ctx).status == PASS
    assert blocked_check_ids(clean_ctx) == set()

    mutated_ctx = make(real["observations"][-1]["m"] * 10000)
    assert check_unit_magnitude(mutated_ctx).status == BLOCK
    # Documented side-catch: a 10,000x slip on the level alone also makes the
    # UNCHANGED published m_yoy imply an impossible prior-year level via
    # gate_a.yoy_base_tolerance's own "off > 50%" branch -- a real, related
    # consequence of the same corruption, not a false positive.
    blocked = blocked_check_ids(mutated_ctx)
    assert "gate_a.unit_magnitude" in blocked
    assert blocked <= {"gate_a.unit_magnitude", "gate_a.yoy_base_tolerance"}


# ===========================================================================
# 2. sign_flip -- YoY -0.6 -> +0.6 -> gate_a.yoy_base_tolerance and/or
# gate_a.seasonal_z WARN+.
# ===========================================================================


def test_mut_sign_flip(tmp_path):
    real = load_fixture_series("mut-retail-total")
    real_history = copy.deepcopy(real)
    real_history["observations"] = real_history["observations"][:-1]
    period = real["observations"][-1]["period"]
    assert real["observations"][-1]["m_yoy"] == -0.6  # the exact value the task spec names

    def make(m_yoy, ytd_yoy):
        staged = copy.deepcopy(real)
        staged["observations"][-1]["m_yoy"] = m_yoy
        staged["observations"][-1]["ytd_yoy"] = ytd_yoy
        batch = make_batch([touch("mut-retail-total", period, m_yoy=m_yoy, ytd_yoy=ytd_yoy)])
        return make_context(
            tmp_path / f"case-{m_yoy}",
            real_overrides={"mut-retail-total": real_history},
            staged_overrides={"mut-retail-total": staged},
            batch=batch,
            today=TODAY,
            archive_files={"nbs-retail": ["rel:test"]},
        )

    clean_ctx = make(-0.6, -0.6)
    assert check_seasonal_z(clean_ctx).status == PASS  # z==0.0: matches a perfectly flat -0.6% history exactly
    assert check_yoy_base_tolerance(clean_ctx).status == PASS
    assert blocked_check_ids(clean_ctx) == set()

    mutated_ctx = make(0.6, 0.6)
    # gate_a.yoy_base_tolerance does NOT catch this one empirically: the level
    # is untouched, so its |published - level-derived| gap is only ~1.2pp,
    # under the default 3.0pp tolerance. gate_a.seasonal_z DOES catch it: the
    # flat -0.6%-every-month history (see module docstring) gives a
    # median-absolute-deviation of exactly 0, so any departure from -0.6% is
    # an infinite z-score. This is the "and/or" the task spec allows for.
    assert check_yoy_base_tolerance(mutated_ctx).status == PASS
    seasonal = check_seasonal_z(mutated_ctx)
    assert seasonal.status == BLOCK
    assert any("inf" in f.message for f in seasonal.findings)
    assert blocked_check_ids(mutated_ctx) == {"gate_a.seasonal_z"}


def test_mut_sign_flip_gate_b_archive_gap(tmp_path):
    """GATE GAP: gate_b.archive_independent_sample does NOT catch this same
    sign flip against the archived HTML source, even though the task spec
    expects it to. Root cause, confirmed empirically (see pipeline/audit/
    kernel.py's _candidate_strings): a NEGATIVE candidate value gets
    additional 下降/负-prefixed search strings, but a POSITIVE candidate is
    just the bare magnitude ("0.6") -- so flipping the stored m_yoy/ytd_yoy
    from -0.6 to +0.6 still finds the substring "0.6" sitting right next to
    "下降0.6%" in the archived page and reports a false PASS instead of a
    mismatch. The fuzzy matcher verifies a NUMBER was printed near the label;
    it does not verify which directional verb (上涨/下降) it followed.
    xfail(strict=True): if this is ever fixed, this assertion starts passing
    and pytest will flag the newly-unnecessary xfail marker (XPASS) rather
    than silently keep hiding it.
    """
    repo_dir = copy_mutation_repo(tmp_path)
    path = repo_dir / "data" / "series" / "mut-retail-total.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    last = data["observations"][-1]
    assert last["m_yoy"] == -0.6
    last["m_yoy"] = 0.6
    last["ytd_yoy"] = 0.6
    path.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")

    report = archive_independent_sample.run(make_ctx(repo_dir, samples_per_section=25))
    hits = {f.field: f.status for f in report.findings if f.series == "mut-retail-total" and f.period == "2026-06"}
    assert hits, "mut-retail-total@2026-06 was not sampled at all"

    if all(status == "pass" for status in hits.values()):
        pytest.xfail(
            "GATE GAP: gate_b.archive_independent_sample cannot distinguish a "
            "YoY sign flip from the correct value when the archived page's "
            "magnitude text is unchanged -- kernel.py's positive-value "
            "candidate strings carry no directional (上涨/下降) prefix, only "
            "negative ones do. A sign-flipped published YoY silently PASSes."
        )
    assert any(status in ("block", "warn") for status in hits.values())


