# 8. revision_flood -- 50 historical values "revised" in one staged batch ->
# gate_a.revision_flood BLOCK.
# ===========================================================================


def test_mut_revision_flood(tmp_path):
    real = load_fixture_series("mut-retail-total")

    def build(n_periods: int, delta: float = 0.1):
        staged = copy.deepcopy(real)
        revisions = []
        for obs in staged["observations"][:n_periods]:
            old_m, old_ytd = obs["m"], obs["ytd"]
            obs["m"] = round(old_m + delta, 4)
            obs["ytd"] = round(old_ytd + delta, 4)
            revisions.append({"period": obs["period"], "measure": "m", "old": old_m, "new": obs["m"], "revised_on": TODAY.isoformat(), "source": "rel:test-revision", "series_id": "mut-retail-total"})
            revisions.append({"period": obs["period"], "measure": "ytd", "old": old_ytd, "new": obs["ytd"], "revised_on": TODAY.isoformat(), "source": "rel:test-revision", "series_id": "mut-retail-total"})
        return staged, revisions

    staged_clean, revisions_clean = build(1)  # 2 revisions -- comfortably under max_per_release=6
    ctx_clean = make_context(tmp_path / "clean", staged_overrides={"mut-retail-total": staged_clean}, normalize_report=NormalizeReport(revisions=revisions_clean), today=TODAY)
    assert check_revision_flood(ctx_clean).status == PASS
    assert blocked_check_ids(ctx_clean) == set()

    staged_flood, revisions_flood = build(25)  # 50 revisions, matching the task spec's own number
    assert len(revisions_flood) == 50
    ctx_flood = make_context(tmp_path / "flood", staged_overrides={"mut-retail-total": staged_flood}, normalize_report=NormalizeReport(revisions=revisions_flood), today=TODAY)
    result = check_revision_flood(ctx_flood)
    assert result.status == BLOCK
    assert result.findings[0].needs_ack
    assert blocked_check_ids(ctx_flood) == {"gate_a.revision_flood"}


