# ===========================================================================
# 4. measure_swap -- m and ytd values exchanged -> gate_a.ytd_arithmetic
# (+unit_magnitude if magnitudes differ enough -- verified empirically not to
# here: m grows ~6x, well under the x100 unit_magnitude threshold).
# ===========================================================================


def test_mut_measure_swap(tmp_path):
    real = load_fixture_series("mut-retail-total")
    last = real["observations"][-1]
    prior = real["observations"][-2]

    def make(swap: bool):
        staged = copy.deepcopy(real)
        staged_last = staged["observations"][-1]
        if swap:
            staged_last["m"], staged_last["ytd"] = staged_last["ytd"], staged_last["m"]
        batch = make_batch([
            touch("mut-retail-total", staged_last["period"], m=staged_last["m"], ytd=staged_last["ytd"]),
            touch("mut-retail-total", prior["period"], m=prior["m"], ytd=prior["ytd"]),  # same batch -> BLOCK not WARN
        ])
        return make_context(
            tmp_path / f"case-{swap}",
            real_overrides={"mut-retail-total": real},
            staged_overrides={"mut-retail-total": staged},
            batch=batch,
            today=TODAY,
        )

    clean_ctx = make(False)
    assert check_ytd_arithmetic(clean_ctx).status == PASS
    assert blocked_check_ids(clean_ctx) == set()

    mutated_ctx = make(True)
    result = check_ytd_arithmetic(mutated_ctx)
    assert result.status == BLOCK
    # after the swap, the "ytd" field on file holds what was originally "m"
    assert f"ytd({last['period']})={last['m']}" in result.findings[0].message
    # Documented side-catch: the same swap also makes the unchanged m_yoy/
    # ytd_yoy imply an impossible prior-year level in BOTH directions via
    # gate_a.yoy_base_tolerance -- a genuine consequence of the swap, not an
    # unrelated false positive. gate_a.unit_magnitude stays quiet: ytd(=
    # 4643.8's true magnitude, now living in "m") vs m(=27368.7, now living in
    # "ytd") is only a ~6x jump, well under the x100 unit-slip threshold.
    blocked = blocked_check_ids(mutated_ctx)
    assert "gate_a.ytd_arithmetic" in blocked
    assert blocked <= {"gate_a.ytd_arithmetic", "gate_a.yoy_base_tolerance"}
    assert check_unit_magnitude(mutated_ctx).status == PASS


