"""Mutation-testing harness for the two accuracy gates: pipeline/validate/
(Gate A, ingest-time, staged-batch API) and pipeline/audit/ (Gate B, post-
build, data/+site-data/ API).

The premise: it is not enough that Gate A/Gate B's own unit tests pass --
this module proves the gates actually CATCH corruption, by taking one clean,
internally-consistent synthetic mini-repo (pipeline/tests/fixtures/mutation/
repo/, covering a monthly level+ytd retail-like series, a CPI-like index with
a rebase break, a ytd-only FAI-like series, a quarterly income-like series
with real_yoy, a 70-city panel, a derived ratio, a DG-sourced series with
archived raw responses, and an HTML-sourced series with an archived fixture
page) where BOTH gates pass clean, then applying one deliberate, named
corruption at a time and asserting:

  (a) the intended check catches it, at the expected severity;
  (b) the SAME construction with the corruption reverted -- built the exact
      same way, not just "the shared control elsewhere" -- still passes (so a
      check that simply always blocks would not silently satisfy this test);
  (c) no OTHER, unrelated check false-positives; a full scan of every other
      gate_a.*/gate_b.* check's status is asserted to be a documented subset
      (a check that fires for a genuinely-related reason -- e.g. an
      impossible-math yoy_base_tolerance BLOCK alongside a raw unit_magnitude
      BLOCK for the same 10,000x slip -- is recorded as an accepted side-catch,
      not hidden).

Fixture construction notes (see pipeline/tests/fixtures/mutation/repo/ itself
for the generated data): mut-retail-total's YoY history is pinned to EXACTLY
-0.6% for every 2025/2026 month by construction (every month's level is the
same calendar month one year prior, times exactly 0.994, both rounded to the
series' own display precision) -- this makes gate_a.seasonal_z's robust_z
history perfectly flat (MAD==0), so the sign_flip mutation's before/after
(z==0.0 vs z==+inf) is unambiguous rather than dependent on a hand-tuned
tolerance. site-data/ was generated by actually running `python -m
pipeline.build` against this fixture's data/ (mirrors pipeline/tests/
fixtures/audit/clean_repo's own convention -- see test_audit_helpers.py).

Isolation: this module owns pipeline/tests/test_mutation_gates.py and
pipeline/tests/fixtures/mutation/ only. It reuses pipeline/tests/
_validate_helpers.py's write_series/touch/make_batch/make_test_config/
make_test_calendar verbatim (only `make_context`'s hardcoded fixture-data-dir
plumbing is re-pointed at this module's own fixture, since that one helper
bakes in pipeline/tests/fixtures/validate/data specifically) and pipeline/
tests/test_audit_helpers.py's make_ctx verbatim (it is already generic over
repo_dir + labels). It talks to pipeline.validate/pipeline.audit's public
check functions directly -- never pipeline.runner -- to stay clear of
runner.py/field_map.yaml/build.py while those are under concurrent edit.
"""
