def gate_b_blocked_check_ids(ctx) -> set[str]:
    """Every gate_b.* check id (excluding build_determinism, which needs its
    own repo_root=REAL_REPO_ROOT context -- see test_control_gate_b_build_
    determinism_passes_clean) whose run against `ctx` has_block()."""
    out = set()
    for module in CHECK_MODULES:
        if module is build_determinism:
            continue
        if module.run(ctx).has_block():
            out.add(module.CHECK_ID)
    return out


